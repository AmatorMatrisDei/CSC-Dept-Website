import { supabase } from "@/lib/supabase";
import type { Course, Degree, PlannerData, SuggestedSemester } from "./types";

// The catalog (courses and each major's suggested plan) lives in the database so admins can edit
// it. It is read once per page load and kept until an admin saves a change.
let cached: Promise<PlannerData> | undefined;

const COURSE_COLUMNS =
  "id, code, title, credits, credits_max, prerequisite_groups, corequisites, offered, offered_years, prerequisite_text, corequisite_text, offered_text, catalog_url, description";

function client() {
  if (!supabase) throw new Error("Supabase is not configured.");
  return supabase;
}

export function loadPlannerData(): Promise<PlannerData> {
  cached ??= fetchPlannerData().catch((e) => {
    cached = undefined;
    throw e;
  });
  return cached;
}

async function fetchPlannerData(): Promise<PlannerData> {
  const db = client();
  const [courses, degrees] = await Promise.all([
    db.from("planner_courses").select(COURSE_COLUMNS).order("code"),
    db.from("planner_degrees").select("id, name, degree, total_credits, catalog_url, auto_generated, semesters").order("sort_order"),
  ]);
  if (courses.error) throw courses.error;
  if (degrees.error) throw degrees.error;
  return {
    courses: new Map(courses.data.map((c): [string, Course] => [c.id, c as unknown as Course])),
    degrees: degrees.data.map(
      (d): Degree => ({
        id: d.id,
        name: d.name,
        degree: d.degree,
        totalCredits: d.total_credits,
        catalogUrl: d.catalog_url,
        autoGenerated: d.auto_generated,
        semesters: d.semesters as unknown as SuggestedSemester[],
      }),
    ),
  };
}

export const forgetPlannerData = () => {
  cached = undefined;
};

// Admin saves. The database rejects anyone else; each returns an error message or null.
function failure(error: { message: string } | null, rows?: unknown[] | null): string | null {
  if (error) return "Could not save: " + error.message;
  if (rows && !rows.length) return "Could not save: you may not have permission.";
  forgetPlannerData();
  return null;
}

export async function saveCourse(course: Course): Promise<string | null> {
  const { data, error } = await client().from("planner_courses").upsert(course as never).select("id");
  return failure(error, data);
}

export async function deleteCourse(id: string): Promise<string | null> {
  const { data, error } = await client().from("planner_courses").delete().eq("id", id).select("id");
  return failure(error, data);
}

export async function saveSuggestedPlan(degreeId: string, semesters: SuggestedSemester[]): Promise<string | null> {
  const { data, error } = await client()
    .from("planner_degrees")
    .update({ semesters: semesters as unknown as never })
    .eq("id", degreeId)
    .select("id");
  return failure(error, data);
}
