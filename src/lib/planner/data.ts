import { supabase } from "@/lib/supabase";
import type { Catalog, Course, Degree, PlannerData, ProgramKind, Requirement, SuggestedSemester } from "./types";

// The catalogs (each year's courses and programs) live in the database so admins can edit them.
// Each year is read once per page load and kept until an admin saves a change to it.
let catalogs: Promise<Catalog[]> | undefined;
const cached = new Map<string, Promise<PlannerData>>();

const COURSE_COLUMNS =
  "catalog_year, id, code, title, credits, credits_max, prerequisite_groups, corequisites, offered, offered_years, prerequisite_text, corequisite_text, offered_text, catalog_url, description";

function client() {
  if (!supabase) throw new Error("Supabase is not configured.");
  return supabase;
}

// The fall a catalog year starts: 2025 for "2025-2026".
export const firstFall = (year: string) => Number(year.slice(0, 4));
export const yearLabel = (year: string) => year.replace("-", "–");

// Oldest first.
export function loadCatalogs(): Promise<Catalog[]> {
  catalogs ??= (async () => {
    const { data, error } = await client().from("planner_catalogs").select("year, name, catalog_url").order("year");
    if (error) throw error;
    return data.map((c) => ({ year: c.year, name: c.name, catalogUrl: c.catalog_url }));
  })().catch((e) => {
    catalogs = undefined;
    throw e;
  });
  return catalogs;
}

export function loadPlannerData(year: string): Promise<PlannerData> {
  let data = cached.get(year);
  if (!data) {
    data = fetchPlannerData(year).catch((e) => {
      cached.delete(year);
      throw e;
    });
    cached.set(year, data);
  }
  return data;
}

async function fetchPlannerData(year: string): Promise<PlannerData> {
  const db = client();
  const [list, courses, degrees] = await Promise.all([
    loadCatalogs(),
    db.from("planner_courses").select(COURSE_COLUMNS).eq("catalog_year", year).order("code"),
    db
      .from("planner_degrees")
      .select("id, name, degree, kind, total_credits, catalog_url, auto_generated, semesters, requirements, notes")
      .eq("catalog_year", year)
      .order("sort_order"),
  ]);
  if (courses.error) throw courses.error;
  if (degrees.error) throw degrees.error;
  const catalog = list.find((c) => c.year === year);
  if (!catalog) throw new Error(`There is no ${year} catalog.`);
  return {
    catalog,
    courses: new Map(courses.data.map((c): [string, Course] => [c.id, c as unknown as Course])),
    degrees: degrees.data.map(
      (d): Degree => ({
        id: d.id,
        name: d.name,
        degree: d.degree,
        kind: d.kind as ProgramKind,
        totalCredits: d.total_credits,
        catalogUrl: d.catalog_url,
        autoGenerated: d.auto_generated,
        semesters: d.semesters as unknown as SuggestedSemester[],
        requirements: d.requirements as unknown as Requirement[],
        notes: d.notes,
      }),
    ),
  };
}

export const forgetPlannerData = (year: string) => {
  cached.delete(year);
};

// Admin saves. The database rejects anyone else; each returns an error message or null.
function failure(year: string, error: { message: string } | null, rows?: unknown[] | null): string | null {
  if (error) return "Could not save: " + error.message;
  if (rows && !rows.length) return "Could not save: you may not have permission.";
  forgetPlannerData(year);
  return null;
}

export async function saveCourse(course: Course): Promise<string | null> {
  const { data, error } = await client()
    .from("planner_courses")
    .upsert(course as never, { onConflict: "catalog_year,id" })
    .select("id");
  return failure(course.catalog_year, error, data);
}

export async function deleteCourse(year: string, id: string): Promise<string | null> {
  const { data, error } = await client().from("planner_courses").delete().eq("catalog_year", year).eq("id", id).select("id");
  return failure(year, error, data);
}

export async function saveSuggestedPlan(year: string, degreeId: string, semesters: SuggestedSemester[]): Promise<string | null> {
  const { data, error } = await client()
    .from("planner_degrees")
    .update({ semesters: semesters as unknown as never })
    .eq("catalog_year", year)
    .eq("id", degreeId)
    .select("id");
  return failure(year, error, data);
}
