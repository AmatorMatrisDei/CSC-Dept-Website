// Shapes for the degree planner (experimental). The data comes from the Franciscan catalog and lives
// in src/data/planner/*.json, trimmed to what the planner uses.

export type Course = {
  id: string;
  code: string;
  title: string;
  credits: number;
  prerequisites: string[];
  corequisites: string[];
  offered: string[];
};

// One line in a semester: either a named course, or a core "slot" such as "Philosophy Core" that the
// student fills in later.
export type SuggestedEntry = { course: string } | { slot: string; credits: number };

export type SuggestedSemester = {
  year: number;
  term: "Fall" | "Spring";
  note: string | null;
  entries: SuggestedEntry[];
};

export type Degree = {
  id: string;
  name: string;
  degree: string;
  totalCredits: number;
  catalogUrl: string;
  autoGenerated: boolean;
  semesters: SuggestedSemester[];
};

// A line in the student's own plan. `course` is null for an unfilled core slot.
export type PlanItem = { key: string; course: string | null; slot: string | null; credits: number };

export type Plan = PlanItem[][];

export type PlannerData = { courses: Map<string, Course>; degrees: Degree[] };
