// Shapes for the degree planner (experimental). The catalog is stored in the database tables
// planner_catalogs, planner_courses and planner_degrees, which admins edit. Each catalog year
// (the year a student started) has its own courses and programs.

// One prerequisite group: met by any one of `courses` done or planned earlier (or in the same term
// when `concurrent`), or by `other`, something outside the plan such as high school math. A course
// needs every one of its groups met. "MTH 220 and either CSC 144 or CSC 171" is two groups.
export type PrerequisiteGroup = { courses: string[]; other?: string; concurrent?: boolean };

export type Term = "fall" | "spring" | "summer";

// One catalog year, such as "2025-2026". A student plans with the catalog of the year they started.
export type Catalog = { year: string; name: string; catalogUrl: string | null };

// Field names match the planner_courses columns, so a Course saves as it is.
export type Course = {
  catalog_year: string;
  id: string;
  code: string;
  title: string;
  credits: number;
  credits_max: number | null; // variable-credit courses (internships, 1 to 6); `credits` is the least
  prerequisite_groups: PrerequisiteGroup[];
  corequisites: string[];
  offered: string[]; // terms it runs in; empty means any term
  offered_years: Partial<Record<Term, "every" | "odd" | "even">>; // "Odd falls, every spring"
  prerequisite_text: string | null; // the catalog's wording, which also covers standing and permission
  corequisite_text: string | null;
  offered_text: string | null;
  catalog_url: string | null;
  description: string | null; // a short note on what the course covers, written by faculty
};

// One line in a semester: either a named course, or a core "slot" such as "Philosophy Core" that the
// student fills in later.
export type SuggestedEntry = { course: string } | { slot: string; credits: number };

export type SuggestedSemester = {
  year: number;
  term: "Fall" | "Spring";
  note: string | null;
  entries: SuggestedEntry[];
};

// One line of what a program requires. Met by all the courses of any one option ("CHM 111 and
// CHM 116, or CHM 141"). A requirement with only a label (an elective, a core area) is the
// student's to fill, so the planner lists it without checking it.
export type Requirement = { label?: string; credits?: number; options?: string[][] };

export type ProgramKind = "major" | "pre_engineering" | "minor";

// A major, a pre-engineering transfer program, or a minor. Minors have requirements but no
// suggested semesters; pre-engineering plans cover the years at Franciscan (4 or 6 semesters).
export type Degree = {
  id: string;
  name: string;
  degree: string;
  kind: ProgramKind;
  totalCredits: number;
  catalogUrl: string | null;
  autoGenerated: boolean;
  semesters: SuggestedSemester[];
  requirements: Requirement[];
  notes: string[];
};

// A line in the student's own plan. `course` is null for an unfilled core slot.
export type PlanItem = { key: string; course: string | null; slot: string | null; credits: number };

export type Plan = PlanItem[][];

export type PlannerData = { catalog: Catalog; courses: Map<string, Course>; degrees: Degree[] };
