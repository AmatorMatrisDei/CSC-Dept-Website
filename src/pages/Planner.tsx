import { useMemo, useState } from "react";
import { useAsync, useTitle } from "@/lib/hooks";
import { loadPlannerData } from "@/lib/planner/data";
import {
  MAX_CREDITS,
  addCourse,
  itemCredits,
  moveItem,
  planToCsv,
  removeItem,
  semesterCredits,
  semesterLabel,
  suggestedPlan,
  warnings,
} from "@/lib/planner/plan";
import { clearMyPlan, loadCompleted, loadDegreeId, loadMyPlan, saveCompleted, saveDegreeId, saveMyPlan } from "@/lib/planner/store";
import type { Course, Degree, Plan } from "@/lib/planner/types";

// Experimental degree planner. Shows the recommended four-year sequence for each major and lets a
// student build their own. Everything is kept in the browser; nothing is sent to the site.

const inputClass = "min-h-11 w-full rounded border border-border bg-surface px-3 py-2 text-foreground placeholder:text-muted";
const button ="min-h-11 rounded border border-border bg-surface px-4 py-2 font-medium hover:border-highlight disabled:opacity-60";

function PlanView({ degree, courses, completed, onToggle }: { degree: Degree; courses: Map<string, Course>; completed: Set<string>; onToggle: (id: string) => void }) {
  const suggested = useMemo(() => suggestedPlan(degree), [degree]);
  const [mode, setMode] = useState<"suggested" | "mine">("suggested");
  const [mine, setMine] = useState<Plan>(() => loadMyPlan(degree.id, (p) => p.length === suggested.length) ?? suggested);
  const [search, setSearch] = useState("");
  const [target, setTarget] = useState(0);

  const plan = mode === "mine" ? mine : suggested;
  const editing = mode === "mine";
  const problems = useMemo(() => (editing ? warnings(mine, courses, completed) : []), [editing, mine, courses, completed]);
  const total = plan.reduce((sum, items) => sum + semesterCredits(items, courses), 0);

  function change(next: Plan) {
    setMine(next);
    saveMyPlan(degree.id, next);
  }

  function download() {
    const url = URL.createObjectURL(new Blob([planToCsv(plan, courses)], { type: "text/csv" }));
    const link = document.createElement("a");
    link.href = url;
    link.download = `${degree.id}-plan.csv`;
    link.click();
    URL.revokeObjectURL(url);
  }

  const placed = new Set(mine.flat().flatMap((i) => (i.course ? [i.course] : [])));
  const query = search.trim().toLowerCase();
  const matches = query
    ? [...courses.values()].filter((c) => !placed.has(c.id) && (c.code.toLowerCase().includes(query) || c.title.toLowerCase().includes(query))).slice(0, 8)
    : [];

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-wrap items-center gap-2">
        <div role="group" aria-label="Plan view" className="flex gap-2">
          {(["suggested", "mine"] as const).map((m) => (
            <button
              key={m}
              type="button"
              aria-pressed={mode === m}
              onClick={() => setMode(m)}
              className={`min-h-11 rounded border px-4 py-2 font-medium ${mode === m ? "border-accent bg-accent text-accent-foreground" : "border-border bg-surface hover:border-highlight"}`}
            >
              {m === "suggested" ? "Suggested plan" : "My plan"}
            </button>
          ))}
        </div>
        <button type="button" onClick={download} className={`${button} sm:ml-auto`}>
          Download (.csv)
        </button>
      </div>

      <p className="text-sm text-muted">
        {editing
          ? "Move courses between semesters, remove them, or add more. Your plan is saved in this browser."
          : `${degree.name} recommended sequence. Your actual schedule may vary.`}{" "}
        {total} credits planned of {degree.totalCredits} needed.
      </p>
      {degree.autoGenerated && (
        <p className="rounded-lg border border-border bg-surface p-3 text-sm">
          This plan was generated from course prerequisites. Check it with your academic advisor.
        </p>
      )}

      {editing && (
        <section aria-labelledby="add-heading" className="flex flex-col gap-3 rounded-lg border border-border bg-surface p-4">
          <h2 id="add-heading" className="text-lg font-semibold">
            Add a course
          </h2>
          <div className="grid gap-3 sm:grid-cols-2">
            <label className="flex flex-col gap-1 text-sm font-medium">
              Search by code or title
              <input value={search} onChange={(e) => setSearch(e.target.value)} className={inputClass} />
            </label>
            <label className="flex flex-col gap-1 text-sm font-medium">
              Add to
              <select value={target} onChange={(e) => setTarget(Number(e.target.value))} className={inputClass}>
                {mine.map((_, s) => (
                  <option key={s} value={s}>
                    {semesterLabel(s)}
                  </option>
                ))}
              </select>
            </label>
          </div>
          {query && matches.length === 0 && <p className="text-sm text-muted">No matching courses left to add.</p>}
          <ul className="flex flex-col gap-2">
            {matches.map((c) => (
              <li key={c.id} className="flex flex-wrap items-center gap-x-3">
                <span className="font-medium">{c.code}</span>
                <span className="text-sm text-muted">
                  {c.title} · {c.credits} cr
                </span>
                <button type="button" onClick={() => change(addCourse(mine, c.id, target))} className="min-h-11 text-sm underline">
                  Add<span className="sr-only"> {c.code}</span>
                </button>
              </li>
            ))}
          </ul>
        </section>
      )}

      {editing && problems.length > 0 && (
        <section aria-labelledby="warn-heading" className="rounded-lg border border-border bg-surface p-4">
          <h2 id="warn-heading" className="text-lg font-semibold">
            {problems.length} thing{problems.length === 1 ? "" : "s"} to check
          </h2>
          <ul className="mt-2 list-disc pl-5 text-sm">
            {problems.map((p, i) => (
              <li key={i}>
                <strong>{courses.get(p.courseId)?.code}</strong>: {p.message}
              </li>
            ))}
          </ul>
        </section>
      )}

      <ol className="grid gap-6 md:grid-cols-2">
        {plan.map((items, s) => {
          const credits = semesterCredits(items, courses);
          const over = credits > MAX_CREDITS;
          return (
            <li key={s} className="flex flex-col gap-3 rounded-lg border border-border p-4">
              <div className="flex flex-wrap items-baseline justify-between gap-2">
                <h2 className="text-lg font-semibold">{semesterLabel(s)}</h2>
                <span className={`text-sm ${over ? "font-semibold" : "text-muted"}`}>
                  {credits} cr{over ? ` (over ${MAX_CREDITS})` : ""}
                </span>
              </div>
              {!editing && degree.semesters[s].note && <p className="text-sm text-muted">{degree.semesters[s].note}</p>}
              {items.length === 0 && <p className="text-sm text-muted">Nothing planned.</p>}
              <ul className="flex flex-col gap-3">
                {items.map((item) => {
                  const course = item.course ? courses.get(item.course) : undefined;
                  const flagged = editing && problems.some((p) => p.courseId === item.course);
                  return (
                    <li key={item.key} className={`flex flex-col gap-1 rounded border p-3 ${item.course ? "border-border" : "border-dashed border-border bg-surface"}`}>
                      <p className="font-medium">
                        {course?.code ?? item.slot ?? item.course}
                        <span className="ml-2 text-sm font-normal text-muted">{itemCredits(item, courses)} cr</span>
                      </p>
                      {course && <p className="text-sm text-muted">{course.title}</p>}
                      {flagged && <p className="text-sm">Check prerequisites below.</p>}
                      <div className="flex flex-wrap items-center gap-x-4">
                        {course && (
                          <label className="flex min-h-11 cursor-pointer items-center gap-2 text-sm">
                            <input type="checkbox" checked={completed.has(course.id)} onChange={() => onToggle(course.id)} className="size-5 accent-[var(--accent)]" />
                            Completed<span className="sr-only"> {course.code}</span>
                          </label>
                        )}
                        {editing && (
                          <>
                            <label className="flex min-h-11 items-center gap-2 text-sm">
                              Move to
                              <select
                                value={s}
                                onChange={(e) => change(moveItem(mine, item.key, Number(e.target.value)))}
                                aria-label={`Move ${course?.code ?? item.slot} to a semester`}
                                className={`${inputClass} !w-auto`}
                              >
                                {mine.map((_, n) => (
                                  <option key={n} value={n}>
                                    {semesterLabel(n)}
                                  </option>
                                ))}
                              </select>
                            </label>
                            <button type="button" onClick={() => change(removeItem(mine, item.key))} className="min-h-11 text-sm underline">
                              Remove<span className="sr-only"> {course?.code ?? item.slot}</span>
                            </button>
                          </>
                        )}
                      </div>
                    </li>
                  );
                })}
              </ul>
            </li>
          );
        })}
      </ol>

      {editing && (
        <p>
          <button
            type="button"
            onClick={() => {
              if (window.confirm("Replace your plan with the suggested one? Courses you marked completed stay marked.")) {
                clearMyPlan(degree.id);
                setMine(suggested);
              }
            }}
            className={button}
          >
            Reset to suggested
          </button>
        </p>
      )}
    </div>
  );
}

export default function Planner() {
  useTitle("Degree planner");
  const data = useAsync(loadPlannerData);
  const [degreeId, setDegreeId] = useState(loadDegreeId);
  const [completed, setCompleted] = useState(loadCompleted);

  if (!data) return <p className="text-muted">Loading…</p>;

  const degree = data.degrees.find((d) => d.id === degreeId) ?? data.degrees.find((d) => d.id === "BS_CS") ?? data.degrees[0];

  function toggle(id: string) {
    const next = new Set(completed);
    if (!next.delete(id)) next.add(id);
    setCompleted(next);
    saveCompleted(next);
  }

  return (
    <div className="flex flex-col gap-6">
      <div className="flex flex-col gap-2">
        <p className="w-fit rounded border border-border px-3 py-1 text-sm">Experimental</p>
        <h1 className="text-3xl font-semibold">Degree planner</h1>
        <p className="max-w-2xl text-muted">
          Plan your four years in the department. Nothing here is an official record, so check your plan with an advisor.
        </p>
      </div>
      <label className="flex max-w-md flex-col gap-1 font-medium">
        Major
        <select
          value={degree.id}
          onChange={(e) => {
            setDegreeId(e.target.value);
            saveDegreeId(e.target.value);
          }}
          className={inputClass}
        >
          {data.degrees.map((d) => (
            <option key={d.id} value={d.id}>
              {d.name}
            </option>
          ))}
        </select>
      </label>
      <PlanView key={degree.id} degree={degree} courses={data.courses} completed={completed} onToggle={toggle} />
    </div>
  );
}
